'use strict';

// Relais Word en MACRO (étude 12/10 : Panda Endpoint Protection met CLAIRE-relais.exe en quarantaine — « trouve un autre moyen
// pour le relais Word »). Aucun programme sur le poste : un module VBA que le collaborateur colle une fois dans Word (Alt+F11,
// modèle Normal). Il tourne DANS Word : toutes les secondes (Application.OnTime), le paragraphe où se trouve le curseur et son
// intitulé partent au serveur quand ils changent (POST /api/relais-word/releve, même jeton que le programme, `format: "texte"`),
// battement toutes les 2 s ; la réponse, en lignes (id, rang du '---', valeur, paragraphe attendu, séparés par des
// tabulations), porte les insertions demandées depuis CLAIRE, faites comme par le programme : '---' repérés sur le TEXTE du
// paragraphe, plage contrôlée avant d'écrire, Ctrl+Z l'annule. Démarre à l'ouverture de Word (AutoExec) ; un jeton refusé
// l'arrête jusqu'au prochain démarrage. Les appels 3CX ne passent pas par la macro (pas de fenêtre à gérer hors de Word).
// Écrit en ASCII (l'éditeur VBA lit le texte collé tel quel, mais un module importé est lu en ANSI).

/** @param {string} texte */
function litteralVba(texte) {
  return '"' + String(texte).replace(/"/g, '""') + '"';
}

// Pure : le module VBA du poste.
/** @param {{ url: string, poste: string, jeton: string }} o @returns {string} */
function moduleVbaRelais({ url, poste, jeton }) {
  return [
    "' Relais CLAIRE pour Word (Aide a la redaction) : envoie a CLAIRE le paragraphe ou se trouve le curseur et y insere les",
    "' valeurs choisies dans CLAIRE (a la place des '---'). Colle dans le modele Normal ; demarre a l'ouverture de Word.",
    "' Pour le retirer : supprimer ce module (Alt+F11, Normal, Modules, CLAIRE, clic droit, Supprimer).",
    'Option Explicit',
    '',
    `Private Const CLAIRE_URL As String = ${litteralVba(url)}`,
    `Private Const CLAIRE_POSTE As String = ${litteralVba(poste)}`,
    `Private Const CLAIRE_JETON As String = ${litteralVba(jeton)}`,
    '',
    'Private dernier As String',
    'Private envoi As Date',
    'Private resultats As String',
    'Private arrete As Boolean',
    '',
    'Public Sub AutoExec()',
    '    CLAIRE_Demarrer',
    'End Sub',
    '',
    'Public Sub CLAIRE_Demarrer()',
    '    arrete = False',
    '    dernier = ""',
    '    On Error Resume Next',
    '    Application.OnTime When:=Now + TimeSerial(0, 0, 1), Name:="CLAIRE_Tour"',
    'End Sub',
    '',
    'Public Sub CLAIRE_Tour()',
    '    On Error Resume Next',
    '    If arrete Then Exit Sub',
    '    Dim titre As String, para As String, avecDoc As Boolean',
    '    Dim p As Paragraph, i As Integer, t As String',
    '    If Documents.Count > 0 Then',
    '        avecDoc = True',
    '        Set p = Selection.Paragraphs(1)',
    '        para = p.Range.Text',
    '        For i = 1 To 15',
    '            Set p = p.Previous',
    '            If p Is Nothing Then Exit For',
    '            t = Normaliser(p.Range.Text)',
    '            If Len(t) > 0 And Len(t) <= 90 And InStr(t, "---") = 0 Then titre = t: Exit For',
    '        Next',
    '    End If',
    '    Err.Clear',
    '    If Len(para) > 4000 Then para = Left(para, 4000)',
    '    Dim cle As String, inchange As Boolean',
    '    cle = titre & "|" & para',
    '    inchange = (cle = dernier)',
    '    If (Not inchange) Or Len(resultats) > 0 Or DateDiff("s", envoi, Now) >= 2 Then',
    '        Dim corps As String',
    '        corps = "{""format"":""texte"",""poste"":" & J(CLAIRE_POSTE) & ",""jeton"":" & J(CLAIRE_JETON) & ",""word"":" & IIf(avecDoc, "true", "false") & ",""inchange"":" & IIf(inchange, "true", "false") & ",""resultats"":[" & resultats & "]"',
    '        If Not inchange Then corps = corps & ",""titre"":" & J(titre) & ",""paragraphe"":" & J(para)',
    '        corps = corps & "}"',
    '        Dim h As Object',
    '        Set h = CreateObject("MSXML2.ServerXMLHTTP.6.0")',
    '        h.setTimeouts 1000, 1000, 2000, 2000',
    '        h.Open "POST", CLAIRE_URL & "api/relais-word/releve", False',
    '        h.setRequestHeader "Content-Type", "application/json; charset=utf-8"',
    '        Err.Clear',
    '        h.send corps',
    '        If Err.Number = 0 Then',
    '            If h.Status = 200 Then',
    '                dernier = cle',
    '                resultats = ""',
    '                envoi = Now',
    '                Dim lignes() As String, k As Integer, champs() As String',
    '                lignes = Split(h.responseText, vbLf)',
    '                For k = 0 To UBound(lignes)',
    '                    If lignes(k) = "renvoyer" Then dernier = ""',
    '                    champs = Split(lignes(k), vbTab)',
    '                    If UBound(champs) = 3 Then',
    '                        If Len(resultats) > 0 Then resultats = resultats & ","',
    '                        resultats = resultats & Inserer(champs(0), CLng(Val(champs(1))), champs(2), champs(3))',
    '                    End If',
    '                Next',
    '            ElseIf h.Status = 403 Then',
    "                ' Jeton refuse (relais reinstalle ailleurs) : arret jusqu'au prochain demarrage de Word.",
    '                arrete = True',
    '                Exit Sub',
    '            End If',
    '        Else',
    '            envoi = Now',
    '        End If',
    '    End If',
    '    Application.OnTime When:=Now + TimeSerial(0, 0, 1), Name:="CLAIRE_Tour"',
    'End Sub',
    '',
    "' Le n-ieme '---' (trois tirets ou plus) du paragraphe, repere sur son texte ; la plage est controlee avant d'ecrire.",
    'Private Function Inserer(id As String, rang As Long, valeur As String, attendu As String) As String',
    '    On Error GoTo Refus',
    '    Dim pr As Range, txt As String, pos As Long, debut As Long, longueur As Long, n As Long, r As Range',
    '    Inserer = "{""id"":" & J(id) & ",""ok"":false,""message"":""Blanc introuvable dans le paragraphe.""}"',
    '    If Documents.Count = 0 Then Exit Function',
    '    Set pr = Selection.Paragraphs(1).Range',
    '    txt = pr.Text',
    '    If Normaliser(txt) <> Normaliser(attendu) Then',
    '        Inserer = "{""id"":" & J(id) & ",""ok"":false,""message"":""Le curseur n est plus dans ce paragraphe.""}"',
    '        Exit Function',
    '    End If',
    '    pos = 1',
    '    n = 0',
    '    Do',
    '        debut = InStr(pos, txt, "---")',
    '        If debut = 0 Then Exit Function',
    '        longueur = 3',
    '        Do While debut + longueur <= Len(txt)',
    '            If Mid(txt, debut + longueur, 1) <> "-" Then Exit Do',
    '            longueur = longueur + 1',
    '        Loop',
    '        If n = rang Then Exit Do',
    '        n = n + 1',
    '        pos = debut + longueur',
    '    Loop',
    '    Set r = pr.Document.Range(pr.Start + debut - 1, pr.Start + debut - 1 + longueur)',
    '    If r.Text <> String(longueur, "-") Then',
    '        Inserer = "{""id"":" & J(id) & ",""ok"":false,""message"":""Blanc introuvable a sa place : copiez la valeur.""}"',
    '        Exit Function',
    '    End If',
    '    r.Text = valeur',
    '    Inserer = "{""id"":" & J(id) & ",""ok"":true}"',
    '    Exit Function',
    'Refus:',
    '    Inserer = "{""id"":" & J(id) & ",""ok"":false,""message"":""Word a refuse l insertion.""}"',
    'End Function',
    '',
    'Private Function Normaliser(s As String) As String',
    '    Dim i As Long, c As String, sortie As String, espace As Boolean',
    '    For i = 1 To Len(s)',
    '        c = Mid(s, i, 1)',
    '        If AscW(c) >= 0 And AscW(c) <= 32 Then',
    '            espace = True',
    '        Else',
    '            If espace And Len(sortie) > 0 Then sortie = sortie & " "',
    '            espace = False',
    '            sortie = sortie & c',
    '        End If',
    '    Next',
    '    Normaliser = sortie',
    'End Function',
    '',
    "' Chaine JSON : guillemets, barres obliques inverses et caracteres de controle echappes.",
    'Private Function J(s As String) As String',
    '    Dim i As Long, c As String, code As Long, sortie As String',
    '    For i = 1 To Len(s)',
    '        c = Mid(s, i, 1)',
    '        code = AscW(c)',
    '        If c = """" Then',
    '            sortie = sortie & "\\"""',
    '        ElseIf c = "\\" Then',
    '            sortie = sortie & "\\\\"',
    '        ElseIf code >= 0 And code < 32 Then',
    '            sortie = sortie & "\\u" & Right("000" & Hex(code), 4)',
    '        Else',
    '            sortie = sortie & c',
    '        End If',
    '    Next',
    '    J = """" & sortie & """"',
    'End Function',
    ''
  ].join('\r\n');
}

// Pure : la réponse d'un relevé pour la macro — « ok », une ligne par insertion (id, rang, valeur, paragraphe attendu, sans
// tabulation ni retour à la ligne), « renvoyer » si le serveur a redémarré.
/** @param {{ id: string, occurrence: number, valeur: string, attendu: string }[]} commandes @param {boolean} renvoyer */
function reponseTexteRelais(commandes, renvoyer) {
  const net = (v) => String(v == null ? '' : v).replace(/[\t\r\n\x0b\x07]+/g, ' ');
  return ['ok'].concat(commandes.map(c => [net(c.id), String(Number(c.occurrence) || 0), net(c.valeur), net(c.attendu)].join('\t')),
    renvoyer ? ['renvoyer'] : []).join('\n');
}

module.exports = { moduleVbaRelais, reponseTexteRelais };
